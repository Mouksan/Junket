/** Вопросы из текста поля: по одному на строку, без пустых и повторов. */
export function parseQuestions(text) {
    const seen = new Set();
    const result = [];
    for (const line of String(text || '').split('\n')) {
        const q = line.trim();
        const key = q.toLowerCase();
        if (!q || seen.has(key)) continue;
        seen.add(key);
        result.push(q);
    }
    return result;
}

function cleanList(list) {
    return {
        id: typeof list?.id === 'string' && list.id ? list.id : makeId(),
        name: typeof list?.name === 'string' ? list.name : '',
        questions: Array.isArray(list?.questions) ? list.questions.filter((q) => typeof q === 'string') : [],
    };
}

/** Все списки (при первом запуске — стартовые). */
export function getBank() {
    const s = getSettings();
    if (!Array.isArray(s.questionBank)) {
        s.questionBank = structuredClone(STARTER_BANK);
        saveSettings();
    }
    s.questionBank = s.questionBank.filter((l) => l && typeof l === 'object').map(cleanList);
    return s.questionBank;
}

export function getList(id) {
    if (!id) return null;
    return getBank().find((l) => l.id === id) || null;
}

/** Вопросы списка, готовые к делу: без пустых и повторов. */
export function listQuestions(list) {
    return parseQuestions((list?.questions || []).join('\n'));
}

export function addList(name = 'Новый список', questions = []) {
    const bank = getBank();
    const list = { id: makeId(), name, questions: [...questions] };
    bank.push(list);
    saveSettings();
    return list;
}

export function updateList(id, patch) {
    const list = getBank().find((l) => l.id === id);
    if (!list) return;
    Object.assign(list, patch);
    saveSettings();
}

export function deleteList(id) {
    const s = getSettings();
    s.questionBank = getBank().filter((l) => l.id !== id);
    saveSettings();
}

/** Ответ модели на «Сочинить список» → вопросы: без номеров, маркеров, кавычек, заголовков и повторов. */
export function parseGeneratedQuestions(text) {
    const lines = String(text || '')
        .replace(/\r\n?/g, '\n')
        .replace(/<(think|thinking|reasoning)>[\s\S]*?<\/\1>/gi, '')
        .replace(/```[a-z]*\n?/gi, '')
        .split('\n')
        .map((line) => line
            .trim()
            .replace(/^(?:\d+\s*[.)]|[-*•–—]|\(\d+\))\s+/, '')
            .replace(/^\*\*(.+)\*\*$/, '$1')
            .replace(/^[«"](.+)[»"]$/, '$1')
            .trim())
        // Шапки вроде «Вот вопросы:» или «## Серьёзные» не нужны
        .filter((line) => line && !/^#+\s/.test(line) && !/:$/.test(line));
    return parseQuestions(lines.join('\n'));
}

/** Случайные n вопросов из списка, в исходном порядке. */
export function pickQuestions(questions, n) {
    if (questions.length <= n) return [...questions];
    const indexes = questions.map((_, i) => i);
    for (let i = indexes.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [indexes[i], indexes[j]] = [indexes[j], indexes[i]];
    }
    return indexes.slice(0, n).sort((a, b) => a - b).map((i) => questions[i]);
}

/** «12 вопросов», «3 вопроса», «1 вопрос». */
export function questionsWord(n) {
    const mod10 = n % 10;
    const mod100 = n % 100;
    if (mod10 === 1 && mod100 !== 11) return 'вопрос';
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'вопроса';
    return 'вопросов';
}
